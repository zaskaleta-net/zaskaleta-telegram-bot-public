// Builds src/sh-place-coordinates.mjs: latitude/longitude of every
// Schleswig-Holstein municipality (AGS), from the Open-Meteo geocoding API
// (GeoNames data). Housing companies and WG-Gesucht give a town but no
// distance; with pinned coordinates the bot measures the distance itself and
// applies the user's radius, without a geocoding request at search time.
//
// Usage (network required): node scripts/build-sh-place-coordinates.mjs
import { writeFile } from 'node:fs/promises';
import { SH_RUNTIME_MUNICIPALITY_ROWS as ROWS } from '../src/sh-municipality-jurisdiction-runtime.mjs';

const ENDPOINT = 'https://geocoding-api.open-meteo.com/v1/search?count=10&language=de&countryCode=DE&name=';
const DELAY_MS = 120;

function baseName(canonical) {
  return String(canonical).replace(/\s*\(.*?\)\s*/gu, ' ').split(',')[0].trim();
}

function nameKey(value) {
  return String(value || '').toLocaleLowerCase('de-DE')
    .replace(/ä/gu, 'ae').replace(/ö/gu, 'oe').replace(/ü/gu, 'ue').replace(/ß/gu, 'ss')
    .normalize('NFKD').replace(/[^a-z0-9]/gu, '');
}

async function lookup(name) {
  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      const response = await fetch(ENDPOINT + encodeURIComponent(name), { signal:AbortSignal.timeout(15000) });
      if (response.ok) return (await response.json()).results || [];
    } catch {}
    await new Promise(resolve => setTimeout(resolve, 1000 * (attempt + 1)));
  }
  return null;
}

// Exact name in Schleswig-Holstein; with several, the one whose district
// (admin3) matches the jurisdiction, else the most populous.
function pick(results, row) {
  const wanted = nameKey(baseName(row.canonical));
  const sh = results.filter(item => item.admin1 === 'Schleswig-Holstein' && nameKey(item.name) === wanted);
  if (!sh.length) return null;
  const jurisdiction = nameKey(row.jurisdiction);
  const inKreis = sh.filter(item => nameKey(item.admin3 || '').includes(jurisdiction) || nameKey(item.admin2 || '').includes(jurisdiction));
  const pool = inKreis.length ? inKreis : sh;
  return pool.sort((a, b) => (b.population || 0) - (a.population || 0))[0];
}

// Eight lookups at a time keep the run to a few minutes.
const CONCURRENCY = 8;
const found = new Map();
let next = 0;
await Promise.all(Array.from({ length:CONCURRENCY }, async () => {
  while (next < ROWS.length) {
    const row = ROWS[next++];
    const results = await lookup(baseName(row.canonical));
    const hit = results ? pick(results, row) : null;
    if (hit) found.set(row.ags, [Math.round(hit.latitude * 1e4) / 1e4, Math.round(hit.longitude * 1e4) / 1e4]);
    await new Promise(resolve => setTimeout(resolve, DELAY_MS));
  }
}));
const entries = ROWS.filter(row => found.has(row.ags)).map(row => [row.ags, ...found.get(row.ags)]);
const missing = ROWS.length - entries.length;

const body = [
  '// AUTO-GENERATED by scripts/build-sh-place-coordinates.mjs. Do not edit by hand.',
  '// Latitude/longitude per Schleswig-Holstein municipality (AGS), Open-Meteo',
  '// geocoding (GeoNames). Municipalities without an exact match are absent.',
  `export const SH_PLACE_COORDINATES_META = Object.freeze({ generatedOn:${JSON.stringify(new Date().toISOString().slice(0, 10))}, municipalities:${ROWS.length}, resolved:${entries.length}, missing:${missing} });`,
  `export const SH_PLACE_COORDINATES = Object.freeze(Object.fromEntries(${JSON.stringify(entries.map(([ags, lat, lon]) => [ags, [lat, lon]]))}));`,
  ''
].join('\n');
await writeFile(new URL('../src/sh-place-coordinates.mjs', import.meta.url), body);
console.log(JSON.stringify({ municipalities:ROWS.length, resolved:entries.length, missing }));
