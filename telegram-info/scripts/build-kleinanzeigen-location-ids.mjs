// Builds src/kleinanzeigen-location-ids.mjs: the Kleinanzeigen location id of
// every Schleswig-Holstein municipality, taken from the portal's own place
// suggestions (s-ort-empfehlungen.json). A free-text "<Ort>, Schleswig-Holstein"
// search resolves about one municipality in seven to the wrong place (the
// whole state, Heidesheim, Hilpoltstein, …); a pinned id cannot.
//
// Usage (network required): node scripts/build-kleinanzeigen-location-ids.mjs
import { writeFile } from 'node:fs/promises';
import { SH_RUNTIME_MUNICIPALITY_ROWS as ROWS } from '../src/sh-municipality-jurisdiction-runtime.mjs';

const ENDPOINT = 'https://www.kleinanzeigen.de/s-ort-empfehlungen.json?query=';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';
const DELAY_MS = 250;
// Labels name the state or, for some towns, the Kreis ("Heide - Dithmarschen").
const SH_SUFFIXES = new Set([
  'schleswig-holstein', 'dithmarschen', 'herzogtum lauenburg', 'nordfriesland', 'ostholstein',
  'kreis ostholstein', 'pinneberg', 'kreis pinneberg', 'plön', 'kreis plön', 'rendsburg-eckernförde',
  'schleswig-flensburg', 'segeberg', 'kreis segeberg', 'steinburg', 'stormarn', 'kreis stormarn'
]);

export function nameKey(value) {
  return String(value || '')
    .toLocaleLowerCase('de-DE')
    .replace(/ä/gu, 'ae').replace(/ö/gu, 'oe').replace(/ü/gu, 'ue').replace(/ß/gu, 'ss')
    .normalize('NFKD').replace(/[^a-z0-9]/gu, '');
}

function baseName(canonical) {
  return String(canonical).replace(/\s*\(.*?\)\s*/gu, ' ').split(',')[0].trim();
}

async function suggestions(query) {
  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      const response = await fetch(ENDPOINT + encodeURIComponent(query), { headers:{ 'user-agent':UA, accept:'application/json' } });
      if (response.ok) return Object.entries(await response.json());
    } catch {}
    await new Promise(resolve => setTimeout(resolve, 1000 * (attempt + 1)));
  }
  return null;
}

function shMatches(entries, canonical) {
  const wanted = new Set([nameKey(canonical), nameKey(baseName(canonical))]);
  return entries
    .map(([key, label]) => {
      const id = /^_(\d{1,12})$/u.exec(key)?.[1];
      const [name, suffix = ''] = String(label).split(/\s+-\s+/u);
      return { id, name:name.trim(), suffix:suffix.trim().toLocaleLowerCase('de-DE') };
    })
    .filter(entry => entry.id && entry.id !== '0' && SH_SUFFIXES.has(entry.suffix) && wanted.has(nameKey(entry.name)));
}

const ids = {};
const unresolved = [];
const nameCount = new Map();
for (const row of ROWS) nameCount.set(nameKey(row.canonical), (nameCount.get(nameKey(row.canonical)) || 0) + 1);

for (const row of ROWS) {
  // Two municipalities with one name cannot be told apart by name alone.
  if (nameCount.get(nameKey(row.canonical)) > 1) { unresolved.push(`${row.canonical} (ambiguous)`); continue; }
  let entries = await suggestions(row.canonical);
  let matches = entries ? shMatches(entries, row.canonical) : [];
  if (!matches.length && baseName(row.canonical) !== row.canonical) {
    await new Promise(resolve => setTimeout(resolve, DELAY_MS));
    entries = await suggestions(baseName(row.canonical));
    matches = entries ? shMatches(entries, row.canonical) : [];
  }
  const distinct = [...new Set(matches.map(match => match.id))];
  if (distinct.length === 1) ids[row.ags] = Number(distinct[0]);
  else unresolved.push(`${row.canonical}${distinct.length ? ` (${distinct.length} ids)` : ''}`);
  await new Promise(resolve => setTimeout(resolve, DELAY_MS));
}

const lines = Object.entries(ids).map(([ags, id]) => `  "${ags}":${id}`);
const body = `// AUTO-GENERATED by scripts/build-kleinanzeigen-location-ids.mjs. Do not edit by hand.
// Kleinanzeigen location id per Schleswig-Holstein municipality (AGS), from the
// portal's own place suggestions. Municipalities without an exact, unambiguous
// Schleswig-Holstein suggestion are absent and keep the free-text search.
export const KLEINANZEIGEN_LOCATION_IDS_META = Object.freeze({ generatedOn:${JSON.stringify(new Date().toISOString().slice(0, 10))}, municipalities:${ROWS.length}, resolved:${lines.length} });
export const KLEINANZEIGEN_LOCATION_IDS = Object.freeze({
${lines.join(',\n')}
});
`;
await writeFile(new URL('../src/kleinanzeigen-location-ids.mjs', import.meta.url), body);
console.log(JSON.stringify({ municipalities:ROWS.length, resolved:lines.length, unresolved:unresolved.length }));
console.log(unresolved.slice(0, 80).join('\n'));
